import type { Tone } from '../types';
import type { CardUpgrade, Pair } from './phase2-types';

type Eight = readonly [string, string, string, string, string, string, string, string];
const pair = (upright: string, reversed: string): Pair => ({ upright, reversed });
const topics = (lines: Eight) => ({
  general: pair(lines[0], lines[1]),
  love: pair(lines[2], lines[3]),
  exam: pair(lines[4], lines[5]),
  weather: pair(lines[6], lines[7]),
});
function card(
  rank: number,
  tone: readonly [Tone, Tone],
  meanings: Eight,
  bites: Eight,
  voices: Eight,
  omens: readonly [string, string],
): CardUpgrade {
  return {
    id: `swords-${String(rank).padStart(2, '0')}`,
    tone: { upright: tone[0], reversed: tone[1] },
    meanings: topics(meanings),
    bite: topics(bites),
    voice: {
      blunt: pair(voices[0], voices[1]),
      oracle: pair(voices[2], voices[3]),
      bestie: pair(voices[4], voices[5]),
      mu: pair(voices[6], voices[7]),
    },
    omen: pair(...omens),
  };
}

