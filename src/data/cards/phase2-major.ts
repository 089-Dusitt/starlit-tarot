import type { CardUpgrade, Pair } from './phase2-types';
import { identities } from './identities';
import type { Tone } from '../types';

type Eight = readonly [string, string, string, string, string, string, string, string];
const pair = (upright: string, reversed: string): Pair => ({ upright, reversed });
function major(
  number: number,
  tone: readonly [Tone, Tone],
  meanings: Eight,
  bite: Eight,
  voice: Eight,
  omen: readonly [string, string],
): CardUpgrade {
  return {
    id: identities[number].id,
    tone: { upright: tone[0], reversed: tone[1] },
    meanings: {
      general: pair(meanings[0], meanings[1]),
      love: pair(meanings[2], meanings[3]),
      exam: pair(meanings[4], meanings[5]),
      weather: pair(meanings[6], meanings[7]),
    },
    bite: {
      general: pair(bite[0], bite[1]),
      love: pair(bite[2], bite[3]),
      exam: pair(bite[4], bite[5]),
      weather: pair(bite[6], bite[7]),
    },
    voice: {
      blunt: pair(voice[0], voice[1]),
      oracle: pair(voice[2], voice[3]),
      bestie: pair(voice[4], voice[5]),
      mu: pair(voice[6], voice[7]),
    },
    omen: pair(omen[0], omen[1]),
  };
}

