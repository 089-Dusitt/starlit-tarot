import type { Suit } from './types';
import type { CoreTopic } from './cards/phase2-types';

export type DailyFate = {
  id: string;
  kind: 'blessing' | 'curse';
  suit: Suit | 'major';
  line: string;
  topic?: CoreTopic;
};

function group(
  suit: DailyFate['suit'],
  kind: DailyFate['kind'],
  lines: readonly string[],
): DailyFate[] {
  return lines.map((line, index) => ({
    id: `${suit}-${kind}-${String(index + 1).padStart(2, '0')}`,
    suit,
    kind,
    line,
  }));
}

