import { identities } from './cards/identities';
import type { CoreTopic } from './cards/phase2-types';
import type { DrawnCard, Position, Suit } from './types';

export interface Combo {
  id: string;
  cards: string[];
  positions?: string[];
  lines: Record<CoreTopic, { medium: string; hot: string }>;
}
type Lines = readonly [string, string, string, string, string, string, string, string];
const major = (n: number) => identities[n].id;
const minor = (suit: Suit, n: number) => `${suit}-${String(n).padStart(2, '0')}`;
function combo(id: string, cards: string[], lines: Lines, positions?: string[]): Combo {
  return {
    id,
    cards,
    ...(positions ? { positions } : {}),
    lines: {
      general: { medium: lines[0], hot: lines[1] },
      love: { medium: lines[2], hot: lines[3] },
      exam: { medium: lines[4], hot: lines[5] },
      weather: { medium: lines[6], hot: lines[7] },
    },
  };
}

