export function findCombos(draw: DrawnCard[], positions?: Position[]): Combo[] {
  return combos.filter((entry) =>
    entry.cards.every((id, member) =>
      draw.some(
        (card, index) =>
          identities[card.index]?.id === id &&
          (!entry.positions || positions?.[index]?.id === entry.positions[member]),
      ),
    ),
  );
}
